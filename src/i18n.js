// Hook: t('key') returns the string in the active language, falling back to EN.
export function useT() {
  const lang = useSelector((state) => state.lang.lang);
  return (key) => STRINGS[lang]?.[key] ?? STRINGS.EN[key] ?? key;
}

export function useLang() {
  return useSelector((state) => state.lang.lang);
}

const WEEKDAYS = {
  EN: ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"],
  GE: ["კვირა", "ორშაბათი", "სამშაბათი", "ოთხშაბათი", "ხუთშაბათი", "პარასკევი", "შაბათი"],
};

// Indexed by Date#getDay() (0 = Sunday), used for routine day chips.
