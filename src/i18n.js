export const MONTHS = {
  EN: ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
  GE: ["იანვარი", "თებერვალი", "მარტი", "აპრილი", "მაისი", "ივნისი", "ივლისი", "აგვისტო", "სექტემბერი", "ოქტომბერი", "ნოემბერი", "დეკემბერი"],
};

export const formatDate = (isoDate, lang) => {
  if (!isoDate) return "";
  const d = new Date(`${isoDate}T00:00:00`);
  if (Number.isNaN(d.getTime())) return isoDate;
  const day = WEEKDAYS[lang]?.[d.getDay()] ?? WEEKDAYS.EN[d.getDay()];
  const month = MONTHS[lang]?.[d.getMonth()] ?? MONTHS.EN[d.getMonth()];
  return lang === "GE"
    ? `${day}, ${d.getDate()} ${month}`
    : `${day}, ${month} ${d.getDate()}`;
};
